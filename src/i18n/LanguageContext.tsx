type TranslationKey = keyof typeof translations.pt;

interface LanguageContextValue {
  language: Language;
  setLanguage: (language: Language) => void;
  toggleLanguage: () => void;
  t: (key: TranslationKey) => string;
}

const LanguageContext = createContext<LanguageContextValue | null>(null);

export const LanguageProvider: React.FC<React.PropsWithChildren> = ({ children }) => {
  const [language, setLanguage] = useState<Language>(() => (
    localStorage.getItem('portfolio-language') === 'en' ? 'en' : 'pt'
  ));

  useEffect(() => {
    localStorage.setItem('portfolio-language', language);
    document.documentElement.lang = language === 'pt' ? 'pt-PT' : 'en';
    document.title = language === 'pt'
      ? 'Manuel Garcia Muanza Fernando · Desenvolvedor Fullstack'
      : 'Manuel Garcia Muanza Fernando · Full-Stack Developer';
    const description = document.querySelector<HTMLMetaElement>('meta[name="description"]');
    if (description) {
      description.content = language === 'pt'
        ? 'Portfólio de Manuel Garcia Muanza Fernando, desenvolvedor Fullstack e estudante de Engenharia Informática em Angola.'
        : 'Portfolio of Manuel Garcia Muanza Fernando, a full-stack developer and Computer Engineering student in Angola.';
    }
  }, [language]);

  const value: LanguageContextValue = {
    language,
    setLanguage,
    toggleLanguage: () => setLanguage((current) => current === 'pt' ? 'en' : 'pt'),
    t: (key) => translations[language][key],
  };

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
};

export const useLanguage = (): LanguageContextValue => {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used inside a LanguageProvider');
  }
  return context;
};
